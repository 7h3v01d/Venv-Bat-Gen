# ---------------------------------------------------------------------------
# PowerShell generators (.ps1 equivalents)
#
# Targets Windows PowerShell 5.1+ (the version shipped with Windows), since
# the whole point of this variant is running on machines where .bat/.cmd
# execution is blocked by policy but .ps1 is allowed. Templates use raw
# strings + token substitution rather than f-strings, since PowerShell
# script blocks use `{ }` constantly and that would mean escaping every
# single one as `{{`/`}}` in an f-string — this way there's nothing to
# accidentally get wrong.
#
# Templates are kept pure ASCII and files are written with a UTF-8 BOM
# (see UTF8_BOM): Windows PowerShell 5.1 reads BOM-less scripts as ANSI.
# ---------------------------------------------------------------------------

_PS1_TOKEN_RE = re.compile(r"__([A-Z][A-Z0-9_]*?)__")


def _render_ps1(template: str, **replacements: str) -> str:
    """Substitute __TOKEN__ placeholders in a raw PowerShell template.

    Single pass: substituted values are never re-scanned, so a project
    called "__VENV_DIR__" stays literal (v3.5.0 replaced sequentially and
    would rewrite it). Unknown tokens are left untouched.
    """
    return _PS1_TOKEN_RE.sub(
        lambda m: replacements.get(m.group(1), m.group(0)), template
    )


#: Returns $true when pyproject.toml declares an installable [project].
_PS1_PROJECT_TABLE_FN = r'''function Test-VbgProjectTable {
    if (-not (Test-Path -LiteralPath 'pyproject.toml')) { return $false }
    return [bool](Select-String -LiteralPath 'pyproject.toml' -Pattern '^\[project\]\s*$' -Quiet)
}'''


def make_run_ps1(cfg: GeneratorConfig) -> str:
    generated_on = _now_stamp()
    pause_fn    = _PS1_PAUSE_FN if cfg.pause_on_exit else ""
    pause_block = "Invoke-VbgPause" if cfg.pause_on_exit else ""

    template = r'''#Requires -Version 5.1
# ============================================================
# Project Runner
# __GENERATOR_LINE__
# Generated on: __GENERATED_ON__
#
# ENTRY_MODE:
#   file   -> python app.py
#   module -> python -m package.module
#   runner -> python -m runner_module [args...]
#   script -> venv Scripts\app.exe [args...]   (console script)
#
# Set $env:CI or $env:VBG_NO_PAUSE to skip pauses.
# ============================================================
Set-Location -LiteralPath $PSScriptRoot
__PAUSE_FN__

$PROJECT_NAME = '__PROJECT_NAME__'
$VENV_DIR     = '__VENV_DIR__'
$ENTRY_MODE   = '__ENTRY_MODE__'
$APP_ENTRY    = '__APP_ENTRY__'
# Literal argument vector - never re-split at runtime.
$RUNNER_ARGS  = __RUNNER_ARGS__

# Windows PowerShell 5.1 (and PowerShell < 7.3 on Windows) pass native
# arguments the legacy way: an argument containing whitespace is wrapped in
# quotes without escaping its trailing backslashes, and empty strings are
# dropped. Pre-compensate for the baked-in RUNNER_ARGS so the program
# receives them exactly.
$legacyArgPassing = ($env:OS -eq 'Windows_NT') -and (
    (-not (Get-Variable -Name PSNativeCommandArgumentPassing -ErrorAction SilentlyContinue)) -or
    ($PSNativeCommandArgumentPassing -eq 'Legacy'))
if ($legacyArgPassing) {
    $RUNNER_ARGS = @($RUNNER_ARGS | ForEach-Object {
        if ($_ -eq '') { '""' }
        elseif (($_ -match '\s') -and ($_ -match '\\+$')) { $_ + $Matches[0] }
        else { $_ }
    })
}

$PY         = Join-Path $PSScriptRoot "$VENV_DIR\Scripts\python.exe"
$SCRIPT_EXE = Join-Path $PSScriptRoot "$VENV_DIR\Scripts\$APP_ENTRY.exe"

if (-not (Test-Path -LiteralPath $PY)) {
    Write-Host "[ERROR] Local venv not found: `"$PY`""
    Write-Host ""
    Write-Host "Fix with:"
    Write-Host "  python -m venv `"$VENV_DIR`""
    Write-Host "  `"$VENV_DIR\Scripts\python.exe`" -m pip install --upgrade pip"
    Write-Host "  `"$VENV_DIR\Scripts\python.exe`" -m pip install -r requirements.txt"
    Write-Host ""
    __PAUSE_BLOCK__
    exit 1
}

if ($ENTRY_MODE -eq "file" -and -not (Test-Path -LiteralPath $APP_ENTRY)) {
    Write-Host "[ERROR] Entry file not found: `"$APP_ENTRY`""
    Write-Host "Edit run.ps1 or run with the correct entry file."
    __PAUSE_BLOCK__
    exit 1
}

if ($ENTRY_MODE -eq "script" -and -not (Test-Path -LiteralPath $SCRIPT_EXE)) {
    Write-Host "[ERROR] Console script not found: `"$SCRIPT_EXE`""
    Write-Host ""
    Write-Host "The venv exists but does not provide this script. Fix with:"
    Write-Host "    .\pip.ps1 install -e ."
    Write-Host "or install the package that provides `"$APP_ENTRY`"."
    __PAUSE_BLOCK__
    exit 1
}

$Host.UI.RawUI.WindowTitle = "$PROJECT_NAME - RUN"
Write-Host "============================================================"
Write-Host " Running : $PROJECT_NAME"
Write-Host " Project : $PSScriptRoot"
Write-Host " Python  : $PY"
Write-Host " Mode    : $ENTRY_MODE"
Write-Host " Entry   : $APP_ENTRY"
if (($ENTRY_MODE -eq "runner" -or $ENTRY_MODE -eq "script") -and $RUNNER_ARGS.Count -gt 0) {
    Write-Host " Args    : $($RUNNER_ARGS -join ' ')"
}
Write-Host "============================================================"
Write-Host ""

switch ($ENTRY_MODE) {
    "module" { & $PY -m $APP_ENTRY @args }
    "runner" { & $PY -m $APP_ENTRY @RUNNER_ARGS @args }
    "script" { & $SCRIPT_EXE @RUNNER_ARGS @args }
    default  { & $PY $APP_ENTRY @args }
}
$EXITCODE = $LASTEXITCODE

Write-Host ""
Write-Host "============================================================"
Write-Host " Process exited with code: $EXITCODE"
Write-Host "============================================================"
__PAUSE_BLOCK__
exit $EXITCODE
'''
    return _render_ps1(
        template,
        GENERATOR_LINE=_GENERATOR_LINE,
        GENERATED_ON=generated_on,
        PAUSE_FN=pause_fn,
        PROJECT_NAME=_ps1_escape(cfg.project_name),
        VENV_DIR=_ps1_escape(cfg.venv_dir),
        ENTRY_MODE=_ps1_escape(cfg.entry_mode),
        APP_ENTRY=_ps1_escape(cfg.app_entry),
        RUNNER_ARGS=_ps1_array_literal(parse_runner_args(cfg.runner_args)),
        PAUSE_BLOCK=pause_block,
    )


