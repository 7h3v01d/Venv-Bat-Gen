class PresetManager:
    """Loads and saves user presets to ~/.venv_bat_gen/presets.json."""

    _STORAGE_DIR  = Path.home() / ".venv_bat_gen"
    _STORAGE_FILE = _STORAGE_DIR / "presets.json"

    # Legacy path — migrate automatically on first load
    _LEGACY_DIR  = Path.home() / ".keystoneai"
    _LEGACY_FILE = _LEGACY_DIR / "venv_generator_presets.json"

    def __init__(self) -> None:
        self._user: dict[str, dict] = {}
        self._load()

    def names(self) -> list[str]:
        return sorted(_BUILTIN_PRESETS) + sorted(n for n in self._user if n not in _BUILTIN_PRESETS)

    def get(self, name: str) -> dict | None:
        if name in _BUILTIN_PRESETS:
            return _BUILTIN_PRESETS[name]
        return self._user.get(name)

    @staticmethod
    def _clean(data: object) -> dict | None:
        """Keep only known fields with the right types; None if unusable."""
        if not isinstance(data, dict):
            return None
        return {k: v for k, v in data.items()
                if k in _PRESET_TYPES and isinstance(v, _PRESET_TYPES[k])}

    def is_builtin(self, name: str) -> bool:
        return name in _BUILTIN_PRESETS

    def save(self, name: str, data: dict) -> None:
        if name in _BUILTIN_PRESETS:
            raise ValueError(f'"{name}" is a built-in preset and cannot be overwritten.')
        self._user[name] = self._clean(data) or {}
        self._persist()

    def delete(self, name: str) -> None:
        if name in _BUILTIN_PRESETS:
            raise ValueError(f'"{name}" is a built-in preset and cannot be deleted.')
        if name not in self._user:
            raise KeyError(name)
        del self._user[name]
        self._persist()

    def _load(self) -> None:
        # Migrate from legacy path if new path doesn't exist yet
        if not self._STORAGE_FILE.exists() and self._LEGACY_FILE.exists():
            try:
                self._STORAGE_DIR.mkdir(parents=True, exist_ok=True)
                import shutil as _shutil
                _shutil.copy2(self._LEGACY_FILE, self._STORAGE_FILE)
            except OSError:
                pass

        if self._STORAGE_FILE.exists():
            try:
                raw = json.loads(self._STORAGE_FILE.read_text(encoding="utf-8"))
            except (json.JSONDecodeError, OSError, UnicodeDecodeError):
                raw = None
            if isinstance(raw, dict):
                # Drop entries that aren't objects, strip unknown/mistyped
                # fields, and never let a user entry shadow a built-in.
                self._user = {
                    str(name): cleaned for name, data in raw.items()
                    if name not in _BUILTIN_PRESETS and (cleaned := self._clean(data)) is not None
                }

    def _persist(self) -> None:
        try:
            self._STORAGE_DIR.mkdir(parents=True, exist_ok=True)
            _atomic_write_bytes(
                self._STORAGE_FILE,
                json.dumps(self._user, indent=2).encode("utf-8"),
            )
        except OSError as exc:
            print(f"[PresetManager] Could not save presets: {exc}", file=sys.stderr)
