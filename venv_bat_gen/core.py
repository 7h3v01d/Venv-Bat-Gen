#: Non-interactive mode. Every generated .bat pauses through %VBG_PAUSE%,
#: which collapses to a no-op `rem` when CI or VBG_NO_PAUSE is set — so the
#: scripts work under CI runners, git hooks, and Task Scheduler (where a bare
#: `pause` with a hidden console waits forever).
_BAT_PAUSE_SETUP = (
    'set "VBG_PAUSE=pause"\n'
    'if defined CI set "VBG_PAUSE=rem"\n'
    'if defined VBG_NO_PAUSE set "VBG_PAUSE=rem"\n'
)

_PS1_PAUSE_FN = r'''function Invoke-VbgPause([string]$Prompt = 'Press Enter to continue') {
    # Skipped under CI / VBG_NO_PAUSE so the script never blocks unattended.
    if (-not $env:CI -and -not $env:VBG_NO_PAUSE) { Read-Host $Prompt | Out-Null }
}'''

#: POSIX pause: only when a human can answer (stdin is a terminal), never
#: under CI / VBG_NO_PAUSE, and never allowed to replace the exit code
#: (v3.5.0's bare `read` returned 1 at EOF, which `set -e` turned into the
#: script's exit status).
_SH_PAUSE = ('if [[ -t 0 && -z "${CI:-}" && -z "${VBG_NO_PAUSE:-}" ]]; then\n'
             '    read -r -p "Press Enter to continue..." _ || true\n'
             'fi')

#: bash: does pyproject.toml declare an installable [project]? (A pyproject
#: that only configures tools — ruff, pytest — is not installable.)
_SH_HAS_PROJECT_TABLE = 'grep -Eq "^\\[project\\][[:space:]]*$" pyproject.toml 2>/dev/null'


