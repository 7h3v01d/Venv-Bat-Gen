@dataclass(frozen=True)
class UpdateAction:
    filename: str
    action:   str   # create | update | unchanged | skip | remove | stale
    reason:   str
    content:  str | None = None


def plan_update(cfg: GeneratorConfig, manifest: Manifest | None, *, force: bool = False,
                adopt: bool = False, prune: bool = False) -> list[UpdateAction]:
    """Decide, per file, what `update` will do. Never writes anything.

    A file is refreshed only when it is provably ours and untouched:
      * its fingerprint matches the one recorded in .vbg.json, or
      * (no manifest) it carries the generator marker and --adopt is given.
    Anything else that differs is skipped unless --force. Files the
    manifest lists that cfg no longer generates are reported as stale, and
    removed only with --prune and only if still untouched.
    """
    outputs = build_previews(cfg)
    recorded = manifest.files if manifest else {}
    actions: list[UpdateAction] = []

    for name, content in outputs.items():
        path = cfg.project_dir / name
        if not path.exists():
            actions.append(UpdateAction(name, "create", "missing", content))
            continue
        actual = _read_text_lenient(path)
        if actual is not None and normalize_content(actual) == normalize_content(content):
            actions.append(UpdateAction(name, "unchanged", "already current", content))
        elif actual is not None and recorded.get(name) == fingerprint(actual):
            actions.append(UpdateAction(name, "update", "unmodified since last generate", content))
        elif force:
            actions.append(UpdateAction(name, "update", "forced (backed up)", content))
        elif manifest is None and adopt and actual and GENERATOR_MARKER in actual:
            actions.append(UpdateAction(name, "update", "adopted (backed up)", content))
        elif actual and GENERATOR_MARKER not in actual:
            actions.append(UpdateAction(name, "skip", "not generated by venv-bat-gen — use --force"))
        elif manifest is None:
            actions.append(UpdateAction(name, "skip", "no .vbg.json record — use --adopt"))
        else:
            actions.append(UpdateAction(name, "skip", "edited since last generate — use --force"))

    for name in sorted(set(recorded) - set(outputs)):
        path = cfg.project_dir / name
        if not path.exists():
            continue
        actual = _read_text_lenient(path)
        if prune and actual is not None and recorded[name] == fingerprint(actual):
            actions.append(UpdateAction(name, "remove", "no longer generated (pruned)"))
        else:
            why = "no longer generated — use --prune to remove" if actual is not None and \
                recorded[name] == fingerprint(actual) else "no longer generated, edited — left alone"
            actions.append(UpdateAction(name, "stale", why))
    return actions


def apply_update(cfg: GeneratorConfig, actions: list[UpdateAction],
                 manifest: Manifest | None) -> Path | None:
    """Carry out a plan from plan_update(). Files that are overwritten or
    removed are first copied to .vbg-backup/<timestamp>/. Rewrites
    .vbg.json. Returns the backup folder, or None if nothing needed one."""
    backup_dir: Path | None = None

    def _backup(path: Path) -> None:
        nonlocal backup_dir
        if backup_dir is None:
            stamp = datetime.now().strftime("%Y%m%d-%H%M%S")
            backup_dir = cfg.project_dir / BACKUP_DIR_NAME / stamp
            n = 1
            while backup_dir.exists():
                n += 1
                backup_dir = cfg.project_dir / BACKUP_DIR_NAME / f"{stamp}-{n}"
            backup_dir.mkdir(parents=True)
        (backup_dir / path.name).write_bytes(path.read_bytes())

    cfg.project_dir.mkdir(parents=True, exist_ok=True)
    recorded = dict(manifest.files) if manifest else {}
    files: dict[str, str] = {}
    for act in actions:
        path = cfg.project_dir / act.filename
        if act.action in {"create", "update"}:
            if path.exists():
                _backup(path)
            _atomic_write_bytes(path, file_bytes(act.filename, act.content or ""),
                                executable=_is_executable_script(act.filename))
            files[act.filename] = fingerprint(act.content or "")
        elif act.action == "unchanged":
            files[act.filename] = fingerprint(act.content or "")
        elif act.action == "remove":
            _backup(path)
            path.unlink()
        elif act.action in {"skip", "stale"} and act.filename in recorded:
            # keep the old record so the file still reads as "edited" next time
            files[act.filename] = recorded[act.filename]

    write_manifest(cfg, files_override=files)
    return backup_dir


