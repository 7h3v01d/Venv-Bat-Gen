# Valid Python module/package name: identifiers separated by dots
MODULE_RE = re.compile(r"^[A-Za-z_][A-Za-z0-9_]*(\.[A-Za-z_][A-Za-z0-9_]*)*$")

# Valid console-script name (venv Scripts/<name>.exe): PyPA allows letters,
# digits, and ._- ; must not start with a dot or hyphen.
SCRIPT_RE = re.compile(r"^[A-Za-z0-9_][A-Za-z0-9._-]*$")

