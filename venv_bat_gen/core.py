def bat_escape(value: str) -> str:
    """Escape characters that would break batch variable assignments."""
    value = value.replace('"', "")
    value = value.replace("%", "%%")
    return value


def _sh_escape(value: str) -> str:
    """Escape a value for safe embedding in a bash double-quoted string."""
    for ch in ('\\', '$', '`', '"'):
        value = value.replace(ch, '\\' + ch)
    return value


def _ps1_escape(value: str) -> str:
    """Escape a value for embedding inside a single-quoted PowerShell string
    literal. Single quotes are PowerShell's literal-string delimiter, so the
    only special case is doubling any embedded single quote — no need to
    worry about $, backticks, or other characters that would trigger
    interpolation inside a double-quoted string."""
    return value.replace("'", "''")


def _b64_encode(text: str, line_endings: str = "\r\n") -> str:
    """Return base64 of text encoded with given line endings."""
    raw = text.replace("\n", line_endings).encode("utf-8")
    return base64.b64encode(raw).decode("ascii")


# ---------------------------------------------------------------------------
# Runner-arg model (v3.5.0)
#
# runner_args stays a plain string in GeneratorConfig / presets / the UI,
# but it is parsed ONCE here with shell-style quoting rules and emitted
# into each template as a literal, individually quoted argument vector.
# The generated scripts never re-split it at runtime, so arguments may
# contain spaces, globs, '!', '&', etc. without being mangled.
# ---------------------------------------------------------------------------

def parse_runner_args(raw: str) -> list[str]:
    """Parse a runner-args string into an argument list.

    Uses POSIX shlex rules: double or single quotes group tokens
    (``--name "My App"`` -> ``['--name', 'My App']``).  Raises ValueError
    on unbalanced quotes.
    """
    raw = raw.strip()
    if not raw:
        return []
    return shlex.split(raw, posix=True)


def runner_args_problem(raw: str) -> str | None:
    """Return a human-readable reason the runner-args string cannot be
    represented safely in all three generated shells, or None if it is fine.

    Fail-closed: anything unparseable or unrepresentable is rejected at
    generation time rather than silently rewritten (the pre-3.5 behaviour
    was to strip double quotes, which corrupted argument boundaries).
    """
    try:
        args = parse_runner_args(raw)
    except ValueError as exc:
        return f"Could not parse runner args ({exc}). Check for unbalanced quotes."
    for arg in args:
        if '"' in arg:
            return (
                "Runner args may not contain a literal double-quote character: "
                "cmd.exe cannot represent an embedded \" inside a quoted argument."
            )
        if "\n" in arg or "\r" in arg:
            return "Runner args may not contain newline characters."
    return None


# ---------------------------------------------------------------------------
# Input validation (v3.6.0) — shared by CLI and GUI, fail-closed
# ---------------------------------------------------------------------------

#: Characters that are never needed in a venv folder name and that at least
#: one of the three target shells cannot carry safely through every template.
_VENV_DIR_FORBIDDEN = set('"%!^&|<>*?\'`$')


def _has_control_chars(value: str) -> bool:
    return any(ord(c) < 32 or ord(c) == 127 for c in value)


def venv_dir_problem(venv_dir: str) -> str | None:
    """Why `venv_dir` can't be used, or None. It must be a plain relative
    path *inside* the project folder: the generated scripts build
    ``<project>\\<venv_dir>\\Scripts\\python.exe`` from it."""
    v = venv_dir.strip()
    if not v:
        return "Venv folder cannot be empty."
    if _has_control_chars(v):
        return "Venv folder may not contain control characters."
    if PureWindowsPath(v).is_absolute() or PureWindowsPath(v).drive or PurePosixPath(v).is_absolute():
        return (f"Venv folder must be a path relative to the project folder, not {v!r}. "
                "The generated scripts always look inside the project.")
    if ".." in re.split(r"[\\/]+", v):
        return "Venv folder may not contain '..' — it must live inside the project folder."
    bad = sorted(set(v) & _VENV_DIR_FORBIDDEN)
    if bad:
        return f"Venv folder may not contain: {' '.join(bad)}"
    return None


def project_name_problem(name: str) -> str | None:
    if not name.strip():
        return "Project name cannot be empty."
    if _has_control_chars(name):
        return "Project name may not contain control characters (e.g. newlines)."
    return None


def entry_problem(entry_mode: str, app_entry: str) -> str | None:
    """Why (entry_mode, app_entry) can't be generated, or None."""
    if entry_mode not in ENTRY_MODES:
        return f"Unknown entry mode {entry_mode!r} (expected one of: {', '.join(ENTRY_MODES)})."
    if not app_entry.strip():
        return "Entry value is required."
    if entry_mode in {"module", "runner"} and not MODULE_RE.match(app_entry):
        return (f"Invalid module name: {app_entry!r}. Module names may only contain "
                "letters, digits, underscores, and dots.")
    if entry_mode == "script" and not SCRIPT_RE.match(app_entry):
        return (f"Invalid console-script name: {app_entry!r}. Use the name from "
                "[project.scripts] — letters, digits, '.', '-', '_' (no .exe, no path).")
    if entry_mode == "file" and (_has_control_chars(app_entry) or '"' in app_entry):
        return "Entry file may not contain double quotes or control characters."
    return None


def config_problem(cfg: GeneratorConfig) -> str | None:
    """First reason `cfg` cannot be generated safely, or None."""
    return (
        project_name_problem(cfg.project_name)
        or venv_dir_problem(cfg.venv_dir)
        or entry_problem(cfg.entry_mode, cfg.app_entry)
        or (runner_args_problem(cfg.runner_args)
            if cfg.entry_mode in {"runner", "script"} else None)
    )


def _bat_quote_arg(arg: str) -> str:
    """Quote one argument for a batch-file command line so the target
    program's argv parser (MSVC CRT / CommandLineToArgvW) sees it exactly.

    * Inside double quotes cmd treats & | < > ^ ! as literal text (run.bat
      never enables delayed expansion), so the only cmd-level translation
      is % -> %% (batch-file parsing).
    * At the CRT level, backslashes are literal *except* when they run into
      a double quote: 2n backslashes + '"' means n backslashes + a closing
      quote. A trailing backslash (``C:\\out\\``) therefore has to be doubled
      or it escapes our closing quote — v3.5.0 got this wrong.
    * Literal double quotes are rejected upstream by runner_args_problem().
    """
    trailing = len(arg) - len(arg.rstrip("\\"))
    body = arg + "\\" * trailing
    return '"' + body.replace("%", "%%") + '"'


def _bat_arg_vector(args: list[str]) -> str:
    """Render args as individually double-quoted cmd.exe tokens."""
    return " ".join(_bat_quote_arg(a) for a in args)


def _sh_array_literal(args: list[str]) -> str:
    """Render args as a bash array literal: ('a' 'b c' ...)."""
    quoted = " ".join("'" + a.replace("'", "'\\''") + "'" for a in args)
    return f"({quoted})"


def _ps1_array_literal(args: list[str]) -> str:
    """Render args as a PowerShell array literal: @('a', 'b c', ...)."""
    if not args:
        return "@()"
    quoted = ", ".join("'" + a.replace("'", "''") + "'" for a in args)
    return f"@({quoted})"


def _display_args(args: list[str]) -> str:
    """One-line display form for banners/log output."""
    return shlex.join(args)


