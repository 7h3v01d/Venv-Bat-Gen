def _prompt_label(name: str) -> str:
    """Project name made safe for a bash PS1 prompt. PS1 is re-expanded every
    time the prompt is drawn ($(...), `...`, \\-escapes), so those
    characters are dropped rather than escaped."""
    return "".join(ch for ch in name if ch not in "$`\\" and ord(ch) >= 32)


