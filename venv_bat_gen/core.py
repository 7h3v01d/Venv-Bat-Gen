def file_bytes(filename: str, content: str) -> bytes:
    """Exact on-disk bytes for a generated file: LF for .sh, CRLF otherwise,
    and a UTF-8 BOM for .ps1 (Windows PowerShell 5.1 needs it)."""
    if filename.endswith(".sh"):
        text = content.replace("\r\n", "\n")
    else:
        text = content.replace("\r\n", "\n").replace("\n", "\r\n")
    if filename.endswith(".ps1"):
        text = UTF8_BOM + text
    return text.encode("utf-8")


def make_self_unpacking_setup_bat(cfg: GeneratorConfig) -> str:
    """
    Generate a single self-unpacking setup.bat that:
      1. Checks Python / uv
      2. Creates / verifies the venv
      3. Installs dependencies
      4. Writes all companion scripts via base64 + certutil decode
         (handles all special characters robustly)
      5. Skips writing any script that already exists (safe to re-run)

    v3.6.0: no delayed expansion (it ate '!' from project names); each temp
    file path is set at top level so plain %TMP_B64% works inside blocks.
    """
    project_name = bat_escape(cfg.project_name)
    venv_dir     = bat_escape(cfg.venv_dir)
    generated_on = _now_stamp()
    uv_tag       = " (uv)" if cfg.use_uv else ""

    # Build the set of companion scripts to embed. We call the individual
    # makers with the SAME cfg so every flag is respected.
    companions = {name: _MAKERS[name](cfg) for name in companion_names(cfg)}

    decode_blocks: list[str] = []
    for filename, content in companions.items():
        b64 = base64.b64encode(file_bytes(filename, content)).decode("ascii")
        # Split b64 into <=76-char lines (certutil friendly)
        lines = [b64[i:i + 76] for i in range(0, len(b64), 76)]

        if filename.endswith(".sh"):
            note = f"\n        echo [INFO] Run: chmod +x {filename}   ^(Linux/macOS^)"
        elif filename.endswith(".ps1"):
            note = ("\n        echo [INFO] If PowerShell blocks scripts, run: "
                    "Set-ExecutionPolicy -Scope Process -ExecutionPolicy Bypass")
        else:
            note = ""

        tmp_name = "vbg_%RANDOM%_" + filename.replace(".", "_") + ".b64"
        block = (
            f"rem ── {filename} ─────────────────────────────────────────────────\n"
            f'set "OUTFILE={filename}"\n'
            f'set "TMP_B64=%TEMP%\\{tmp_name}"\n'
            f'if exist "%OUTFILE%" (\n'
            f'    echo [SKIP] %OUTFILE% already exists\n'
            f') else (\n'
            f'    (\n'
        )
        block += "".join(f"        echo {line}\n" for line in lines)
        block += (
            f'    ) > "%TMP_B64%"\n'
            f'    certutil -decode "%TMP_B64%" "%OUTFILE%" >nul 2>&1\n'
            f'    if exist "%TMP_B64%" del "%TMP_B64%"\n'
            f'    if exist "%OUTFILE%" (\n'
            f'        echo [OK]   %OUTFILE%{note}\n'
            f'    ) else (\n'
            f'        echo [FAIL] %OUTFILE% - certutil decode failed. certutil may be blocked or unavailable.\n'
            f'        set "UNPACK_FAILED=1"\n'
            f'    )\n'
            f')\n'
        )
        decode_blocks.append(block)

    all_decode_blocks = "\n".join(decode_blocks)
    script_list = "  ".join(companions)

    if cfg.use_uv:
        env_check = _BAT_UV_CHECK
        bootstrap = _bat_uv_bootstrap(indent="    ")
    else:
        env_check = _BAT_PYTHON_CHECK
        bootstrap = _bat_pip_bootstrap(indent="    ")

    test_line = ("echo    test.bat   - Run the pytest suite" if cfg.include_test_bat
                 else "rem (test.bat not included)")

    return f'''@echo off
setlocal
cd /d "%~dp0"

rem ============================================================
rem  Project Setup  [self-unpacking]{uv_tag}
rem  {_GENERATOR_LINE}
rem  Generated on: {generated_on}
rem
rem  Ship ONLY this file in your repo.  On first run it:
rem    1. Checks Python{"/ uv" if cfg.use_uv else ""}
rem    2. Creates / verifies the virtual environment
rem    3. Installs dependencies
rem    4. Writes companion scripts beside this file:
rem       {script_list}
rem
rem  Companion scripts are NOT overwritten if they already exist.
rem  Add them to .gitignore to keep your repo tidy
rem  (venv-bat-gen generate --self-unpack --gitignore does it for you).
rem  Exit code: 0 on success, 1 if any step failed.
rem ============================================================

set "PROJECT_NAME={project_name}"
set "VENV_DIR={venv_dir}"
{_BAT_PAUSE_SETUP}set "SETUP_FAILED="
set "UNPACK_FAILED="

title "%PROJECT_NAME% - SETUP"

echo ============================================================
echo  Setup: "%PROJECT_NAME%"{uv_tag}
echo ============================================================
echo.

rem ── 1. Environment check + venv bootstrap ───────────────────
{env_check}

if exist "%VENV_DIR%\\Scripts\\python.exe" (
    echo [INFO] Virtual environment already exists at "%VENV_DIR%\\"
    echo        Skipping creation.
    echo.
) else (
{bootstrap}
)

rem ── 2. Write companion scripts ───────────────────────────────
echo ============================================================
echo  Writing companion scripts...
echo ============================================================
echo.

{all_decode_blocks}
echo.
if defined UNPACK_FAILED set "SETUP_FAILED=1"
{_BAT_SETUP_RESULT}
echo  SETUP COMPLETE
echo.
echo  Companion scripts written (existing files were NOT overwritten).
echo  Add them to .gitignore to keep your repo tidy.
echo.
echo  Next steps:
echo    run.bat    - Launch "%PROJECT_NAME%"
echo    sync.bat   - Reinstall / update dependencies
echo    shell.bat  - Open activated venv shell
echo    doctor.bat - Environment health check
echo    pip.bat    - Project-local pip wrapper
{test_line}
echo ============================================================
%VBG_PAUSE%
exit /b 0
'''


