# .gitignore managed block
# ---------------------------------------------------------------------------

GITIGNORE_BEGIN = "# >>> venv-bat-gen (managed block: regenerated by venv-bat-gen) >>>"
GITIGNORE_END   = "# <<< venv-bat-gen <<<"


def gitignore_entries(cfg: GeneratorConfig) -> list[str]:
    """What the managed block ignores: the venv, update backups, and — in
    repo (self-unpack) mode — the companions setup.bat writes on first run."""
    venv = cfg.venv_dir.replace("\\", "/").strip("/")
    entries = [f"/{venv}/", f"/{BACKUP_DIR_NAME}/"]
    if cfg.self_unpack:
        entries += [f"/{n}" for n in companion_names(cfg)]
    return entries


def update_gitignore(folder: Path, entries: list[str]) -> bool:
    """Create or refresh the managed block in <folder>/.gitignore, leaving
    everything outside it untouched. Returns True if the file changed."""
    path = folder / ".gitignore"
    old = path.read_text(encoding="utf-8") if path.exists() else ""
    block = "\n".join([GITIGNORE_BEGIN, *entries, GITIGNORE_END]) + "\n"
    pattern = re.compile(re.escape(GITIGNORE_BEGIN) + r".*?" + re.escape(GITIGNORE_END) + r"\n?",
                         re.S)
    if pattern.search(old):
        new = pattern.sub(lambda _m: block, old, count=1)
    else:
        sep = "" if not old or old.endswith("\n\n") else ("\n" if old.endswith("\n") else "\n\n")
        new = old + sep + block
    if new == old:
        return False
    path.write_text(new, encoding="utf-8")
    return True


