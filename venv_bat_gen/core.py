def make_run_sh(cfg: GeneratorConfig) -> str:
    project_name = _sh_escape(cfg.project_name)
    venv_dir     = _sh_escape(cfg.venv_dir)
    entry_mode   = _sh_escape(cfg.entry_mode)
    app_entry    = _sh_escape(cfg.app_entry)
    args_array   = _sh_array_literal(parse_runner_args(cfg.runner_args))
    pause_block  = _SH_PAUSE if cfg.pause_on_exit else ""
    generated_on = _now_stamp()

    return f'''#!/usr/bin/env bash
# ============================================================
# Project Runner
# {_GENERATOR_LINE}
# Generated on: {generated_on}
#
# ENTRY_MODE:
#   file   -> python app.py
#   module -> python -m package.module
#   runner -> python -m runner_module [args...]
#   script -> venv bin/app [args...]   (console script)
#
# Pauses only when stdin is a terminal; set CI=1 or VBG_NO_PAUSE=1 to skip.
# ============================================================
set -euo pipefail
cd "$(dirname "$0")"

PROJECT_NAME="{project_name}"
VENV_DIR="{venv_dir}"
ENTRY_MODE="{entry_mode}"
APP_ENTRY="{app_entry}"
# Literal argument vector — never re-split or glob-expanded at runtime.
RUNNER_ARGS={args_array}

PY="$PWD/$VENV_DIR/bin/python"
SCRIPT_BIN="$PWD/$VENV_DIR/bin/$APP_ENTRY"

if [[ ! -x "$PY" ]]; then
    echo "[ERROR] Local venv not found: $PY"
    echo ""
    echo "Create it with:"
    echo "    python3 -m venv \\"$VENV_DIR\\""
    echo "    \\"$VENV_DIR/bin/python\\" -m pip install --upgrade pip"
    echo "    \\"$VENV_DIR/bin/python\\" -m pip install -r requirements.txt"
    exit 1
fi

if [[ "$ENTRY_MODE" == "file" && ! -f "$APP_ENTRY" ]]; then
    echo "[ERROR] Entry file not found: $APP_ENTRY"
    echo "Edit run.sh or specify correct entry point."
    exit 1
fi

if [[ "$ENTRY_MODE" == "script" && ! -x "$SCRIPT_BIN" ]]; then
    echo "[ERROR] Console script not found: $SCRIPT_BIN"
    echo ""
    echo "The venv exists but does not provide this script. Fix with:"
    echo "    ./pip.sh install -e ."
    echo "or install the package that provides \\"$APP_ENTRY\\"."
    exit 1
fi

echo "============================================================"
echo " Running : $PROJECT_NAME"
echo " Project : $PWD"
echo " Python  : $PY"
echo " Mode    : $ENTRY_MODE"
echo " Entry   : $APP_ENTRY"
if [[ "$ENTRY_MODE" == "runner" || "$ENTRY_MODE" == "script" ]]; then
    [[ ${{#RUNNER_ARGS[@]}} -gt 0 ]] && echo " Args    : ${{RUNNER_ARGS[*]}}"
fi
echo "============================================================"
echo ""

EXITCODE=0

# ${{RUNNER_ARGS[@]+...}} guard: safe under `set -u` on bash 3.2 (macOS),
# where expanding an empty array is otherwise a fatal unbound-variable error.
if [[ "$ENTRY_MODE" == "module" ]]; then
    "$PY" -m "$APP_ENTRY" "$@" || EXITCODE=$?
elif [[ "$ENTRY_MODE" == "runner" ]]; then
    "$PY" -m "$APP_ENTRY" ${{RUNNER_ARGS[@]+"${{RUNNER_ARGS[@]}}"}} "$@" || EXITCODE=$?
elif [[ "$ENTRY_MODE" == "script" ]]; then
    "$SCRIPT_BIN" ${{RUNNER_ARGS[@]+"${{RUNNER_ARGS[@]}}"}} "$@" || EXITCODE=$?
else
    "$PY" "$APP_ENTRY" "$@" || EXITCODE=$?
fi

echo ""
echo "============================================================"
echo " Process exited with code: $EXITCODE"
echo "============================================================"
{pause_block}
exit $EXITCODE
'''


