# ---------------------------------------------------------------------------
# .bat generators
#
# cmd.exe rules these templates follow (v3.6.0):
#   * every echo of a user- or filesystem-derived value (%PROJECT_NAME%,
#     %CD%, %PY%, %APP_ENTRY%, ...) is inside double quotes — %-expansion
#     happens *before* cmd looks for & | < > ^, so an unquoted "R&D" or
#     "C:\Tom & Jerry" would split the echo into a second command;
#   * delayed expansion is never enabled (it eats '!' from values);
#   * pauses go through %VBG_PAUSE% (see _BAT_PAUSE_SETUP), always on a
#     line of their own.
# ---------------------------------------------------------------------------

def make_run_bat(cfg: GeneratorConfig) -> str:
    project_name = bat_escape(cfg.project_name)
    venv_dir     = bat_escape(cfg.venv_dir)
    entry_mode   = bat_escape(cfg.entry_mode)
    app_entry    = bat_escape(cfg.app_entry)
    args         = parse_runner_args(cfg.runner_args)
    arg_vector   = _bat_arg_vector(args)
    args_display = bat_escape(_display_args(args))
    launch_args  = (arg_vector + " ") if arg_vector else ""
    pause_block  = "%VBG_PAUSE%\nexit /b %EXITCODE%\n" if cfg.pause_on_exit else "exit /b %EXITCODE%\n"
    generated_on = _now_stamp()

    return fr'''@echo off
setlocal
cd /d "%~dp0"

rem ============================================================
rem  Project Runner
rem  {_GENERATOR_LINE}
rem  Generated on: {generated_on}
rem
rem  ENTRY_MODE:
rem    file   -> python app.py
rem    module -> python -m package.module
rem    runner -> python -m runner_module [args...]
rem    script -> venv Scripts\app.exe [args...]   (console script)
rem
rem  Set CI=1 or VBG_NO_PAUSE=1 to skip all pauses.
rem ============================================================

set "PROJECT_NAME={project_name}"
set "VENV_DIR={venv_dir}"
set "ENTRY_MODE={entry_mode}"
set "APP_ENTRY={app_entry}"
set "RUNNER_ARGS={args_display}"
{_BAT_PAUSE_SETUP}
set "PY=%CD%\%VENV_DIR%\Scripts\python.exe"
set "SCRIPT_EXE=%CD%\%VENV_DIR%\Scripts\%APP_ENTRY%.exe"

if not exist "%PY%" (
    echo [ERROR] Local venv not found: "%PY%"
    echo.
    echo Fix with:
    echo   python -m venv "%VENV_DIR%"
    echo   "%VENV_DIR%\Scripts\python.exe" -m pip install --upgrade pip
    echo   "%VENV_DIR%\Scripts\python.exe" -m pip install -r requirements.txt
    echo.
    %VBG_PAUSE%
    exit /b 1
)

if /I "%ENTRY_MODE%"=="file" if not exist "%APP_ENTRY%" (
    echo [ERROR] Entry file not found: "%APP_ENTRY%"
    echo Edit run.bat or run with the correct entry file.
    %VBG_PAUSE%
    exit /b 1
)

if /I "%ENTRY_MODE%"=="script" if not exist "%SCRIPT_EXE%" (
    echo [ERROR] Console script not found: "%SCRIPT_EXE%"
    echo.
    echo The venv exists but does not provide this script. Fix with:
    echo   pip.bat install -e .
    echo or install the package that provides "%APP_ENTRY%".
    %VBG_PAUSE%
    exit /b 1
)

title "%PROJECT_NAME% - RUN"
echo ============================================================
echo  Running : "%PROJECT_NAME%"
echo  Project : "%CD%"
echo  Python  : "%PY%"
echo  Mode    : %ENTRY_MODE%
echo  Entry   : "%APP_ENTRY%"
if /I "%ENTRY_MODE%"=="runner" echo  Args    : "%RUNNER_ARGS%"
if /I "%ENTRY_MODE%"=="script" echo  Args    : "%RUNNER_ARGS%"
echo ============================================================
echo.

set "EXITCODE=0"

if /I "%ENTRY_MODE%"=="module" (
    "%PY%" -m %APP_ENTRY% %*
) else if /I "%ENTRY_MODE%"=="runner" (
    "%PY%" -m %APP_ENTRY% {launch_args}%*
) else if /I "%ENTRY_MODE%"=="script" (
    "%SCRIPT_EXE%" {launch_args}%*
) else (
    "%PY%" "%APP_ENTRY%" %*
)

set "EXITCODE=%ERRORLEVEL%"

echo.
echo ============================================================
echo  Process exited with code: %EXITCODE%
echo ============================================================
{pause_block}'''


